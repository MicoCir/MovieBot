"""Dataset card generation for the Silver Dataset.

Produces a markdown file documenting version metadata, generation model,
distribution statistics (by suite, split, route, language, difficulty),
and known limitations.
"""

from collections import Counter
from pathlib import Path

from silver_dataset.models.case import SilverCase
from silver_dataset.versioning.integrity import DatasetVersion


def generate_dataset_card(
    version: DatasetVersion,
    cases: list[SilverCase],
    output_path: Path,
) -> Path:
    """Generate silver_dataset_card.md with version, model, distribution stats, and limitations.

    Args:
        version: DatasetVersion metadata for this release.
        cases: All SilverCase instances in the dataset.
        output_path: Directory where silver_dataset_card.md will be written.

    Returns:
        Path to the generated markdown file.
    """
    # Compute distribution statistics
    suite_counts = Counter(case.suite.value for case in cases)
    split_counts = Counter(case.split.value for case in cases)
    route_counts = Counter(case.expected_route.value for case in cases)
    language_counts = Counter(case.language for case in cases)
    difficulty_counts = Counter(case.difficulty.value for case in cases)

    # Build markdown content
    lines: list[str] = []
    lines.append("# Silver Dataset Card")
    lines.append("")
    lines.append("## Version Information")
    lines.append("")
    lines.append(f"- **Version**: {version.version}")
    lines.append(f"- **Checksum (SHA-256)**: `{version.checksum}`")
    lines.append(f"- **Created at**: {version.created_at}")
    lines.append(f"- **Generator model**: {version.model}")
    lines.append(f"- **Prompt version**: {version.prompt_version}")
    lines.append(f"- **Total cases**: {version.total_cases}")
    if version.description:
        lines.append(f"- **Description**: {version.description}")
    lines.append("")

    lines.append("## Distribution Statistics")
    lines.append("")

    # Suite distribution
    lines.append("### By Suite")
    lines.append("")
    lines.append("| Suite | Count | Percentage |")
    lines.append("|-------|-------|------------|")
    total = len(cases) if cases else 1
    for suite, count in sorted(suite_counts.items()):
        pct = count / total * 100
        lines.append(f"| {suite} | {count} | {pct:.1f}% |")
    lines.append("")

    # Split distribution
    lines.append("### By Split")
    lines.append("")
    lines.append("| Split | Count | Percentage |")
    lines.append("|-------|-------|------------|")
    for split, count in sorted(split_counts.items()):
        pct = count / total * 100
        lines.append(f"| {split} | {count} | {pct:.1f}% |")
    lines.append("")

    # Route distribution
    lines.append("### By Expected Route")
    lines.append("")
    lines.append("| Route | Count | Percentage |")
    lines.append("|-------|-------|------------|")
    for route, count in sorted(route_counts.items()):
        pct = count / total * 100
        lines.append(f"| {route} | {count} | {pct:.1f}% |")
    lines.append("")

    # Language distribution
    lines.append("### By Language")
    lines.append("")
    lines.append("| Language | Count | Percentage |")
    lines.append("|----------|-------|------------|")
    for lang, count in sorted(language_counts.items()):
        pct = count / total * 100
        lines.append(f"| {lang} | {count} | {pct:.1f}% |")
    lines.append("")

    # Difficulty distribution
    lines.append("### By Difficulty")
    lines.append("")
    lines.append("| Difficulty | Count | Percentage |")
    lines.append("|------------|-------|------------|")
    for diff, count in sorted(difficulty_counts.items()):
        pct = count / total * 100
        lines.append(f"| {diff} | {count} | {pct:.1f}% |")
    lines.append("")

    # Limitations section
    lines.append("## Known Limitations")
    lines.append("")
    lines.append(
        "- **Silver quality**: Cases are generated by an LLM and have not "
        "undergone exhaustive human review. Labels are derived deterministically "
        "from latent specifications but queries may contain subtle inconsistencies."
    )
    lines.append(
        "- **Local model constraints**: Generated using a local model "
        f"({version.model}) which may produce lower diversity than commercial APIs."
    )
    lines.append(
        "- **Language coverage**: Limited to English and Spanish with "
        "code-switching variants; does not cover other languages."
    )
    lines.append(
        "- **Fixture scope**: Tool output fixtures cover common scenarios "
        "but may not represent the full distribution of real API responses."
    )
    lines.append("")

    # Write to file
    output_path = Path(output_path)
    output_path.mkdir(parents=True, exist_ok=True)
    card_path = output_path / "silver_dataset_card.md"
    card_path.write_text("\n".join(lines), encoding="utf-8")

    return card_path
