"""Latent specification model for the Silver Dataset generation pipeline.

Defines the LatentSpecification model that serves as the pre-generation blueprint
for a test scenario. All labels are derived deterministically from this specification
before the natural language query is generated by the LLM.
"""

from pydantic import BaseModel, Field

from silver_dataset.models.case import (
    Difficulty,
    ExpectedAction,
    ExpectedRoute,
    ExpectedTool,
    Suite,
)


class LatentSpecification(BaseModel):
    """Pre-generation specification that defines completely a test scenario.

    All labels are derived from this specification deterministically before
    the natural language query is generated by the LLM.
    """

    spec_id: str
    suite: Suite
    scenario_family: str
    scenario_type: str
    route: ExpectedRoute
    tool: ExpectedTool
    action: ExpectedAction
    language: str
    response_language: str
    difficulty: Difficulty
    tool_request_template: dict | None = None
    user_constraints: dict = Field(default_factory=dict)
    fixture_id: str | None = None
    variation_type: str | None = None
    seed_scenario_id: str | None = None
    tags: list[str] = Field(default_factory=list)
